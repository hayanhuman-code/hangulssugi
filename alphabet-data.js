    const ink = PU.inkX(raw, sw);
    const dx = round((CELL - (ink[1] - ink[0])) / 2 - ink[0]);
    return raw.map(s => {
      const d = PU.translatePath(s.d, dx, 0);
      return { d: d, start: startOf(d) };
    });
